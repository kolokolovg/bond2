package ru.onlychill.bonds2;

/**
 * Состояние БД главного окна. Определяет доступность пунктов меню и возможность выхода.
 *
 * <ul>
 *   <li>{@link #CLOSED} — БД не открыта: её можно открыть или создать новую;
 *   <li>{@link #OPENING} — БД открывается или создаётся в фоне, включая ожидание согласия на
 *       миграцию: меню заблокировано, чтобы не запустить две операции сразу;
 *   <li>{@link #OPEN} — БД открыта: её можно закрыть;
 *   <li>{@link #MIGRATING} — выполняется миграция с резервной копией: меню заблокировано, выход
 *       отложен.
 * </ul>
 */
enum DbState {
  CLOSED,
  OPENING,
  OPEN,
  MIGRATING;

  /** «Открыть базу»: только когда БД закрыта и никакая операция не идёт. */
  boolean allowsOpen() {
    return this == CLOSED;
  }

  /** «Создать базу…»: только когда БД закрыта и никакая операция не идёт. */
  boolean allowsCreate() {
    return this == CLOSED;
  }

  /** «Закрыть базу»: только когда БД открыта. */
  boolean allowsClose() {
    return this == OPEN;
  }

  /** «Настройки…»: недоступны во время операций с БД. */
  boolean allowsSettings() {
    return this == CLOSED || this == OPEN;
  }
}
