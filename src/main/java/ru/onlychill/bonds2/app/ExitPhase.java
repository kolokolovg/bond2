package ru.onlychill.bonds2.app;

/**
 * Фаза завершения приложения. Заменяет набор независимых флагов: одна фаза читается всеми
 * участниками (интерфейс, сценарий миграции, машина выхода) вместо согласования {@code
 * exiting}/{@code stopped}/{@code exitStarted} между классами.
 *
 * <ul>
 *   <li>{@link #RUNNING} — приложение работает;
 *   <li>{@link #EXITING} — выход начат: повторный запрос игнорируется, диалог миграции не
 *       показывается;
 *   <li>{@link #CONCLUDED} — итог остановки известен: поздние результаты операций игнорируются,
 *       завершение продолжается при любых сбоях интерфейса.
 * </ul>
 */
public enum ExitPhase {
  RUNNING,
  EXITING,
  CONCLUDED
}
